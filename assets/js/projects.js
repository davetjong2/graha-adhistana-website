  src(img, size) { return 'assets/img/' + (size === 'l' ? 'ig/' : 'm/') + img.f; },
  /* intrinsic width/height for the chosen size, for width/height attributes */
  dims(img, size) {
    if (size === 'l') return { w: img.w, h: img.h };
    const s = Math.min(1, 1100 / Math.max(img.w, img.h));
    return { w: Math.round(img.w * s), h: Math.round(img.h * s) };
  },
